import { readdir, readFile, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const videosDirectory = path.join(projectRoot, 'public/io-design/assets/videos');
const outputPath = path.join(projectRoot, 'src/generated/videoByteLengths.ts');
const checkOnly = process.argv.includes('--check');

const filenames = (await readdir(videosDirectory))
  .filter((filename) => filename.toLowerCase().endsWith('.mp4'))
  .sort((a, b) => a.localeCompare(b));

const entries = await Promise.all(filenames.map(async (filename) => {
  const fileStat = await stat(path.join(videosDirectory, filename));
  return [`/io-design/assets/videos/${filename}`, fileStat.size];
}));

const source = [
  '// Generated by scripts/generate-video-byte-lengths.mjs. Do not edit by hand.',
  'export const VIDEO_BYTE_LENGTHS: Record<string, number> = {',
  ...entries.map(([pathname, size]) => `  ${JSON.stringify(pathname)}: ${size},`),
  '};',
  '',
].join('\n');

if (checkOnly) {
  const current = await readFile(outputPath, 'utf8').catch(() => '');
  if (current !== source) {
    console.error('Video byte-length manifest is stale. Run npm run sync:video-manifest.');
    process.exitCode = 1;
  }
} else {
  await writeFile(outputPath, source);
}
